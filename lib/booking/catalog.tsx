"use client";

import { createContext, useContext, useMemo, type CSSProperties, type ReactNode } from "react";
import { useBooking } from "@/lib/booking/store";
import { STAFF_LABEL, THEMES, type SiteSpec, type ThemeDef } from "@/lib/builder/spec";
import { masters as chinorMasters, salon as chinorSalon, services as chinorServices } from "@/lib/data/salon";
import { dictionaries } from "@/lib/i18n/dictionaries";
import type { Master, Salon, Translated } from "@/lib/types";

/**
 * What the booking screens are booking *from*.
 *
 * The flow (services → master → time → contacts) used to import one salon's
 * data directly, which is why only that salon had a working Mini App. Every
 * screen now reads the catalogue from this context instead, so the same flow
 * serves the built-in Chinor module and any tenant generated by the builder.
 */

export interface CatalogGroup {
  id: string;
  title: Translated;
}

export interface CatalogService {
  id: string;
  group: string;
  title: Translated;
  description?: Translated;
  durationMin: number;
  priceSum: number;
  popular?: boolean;
}

/** Content a generated site has around its booking flow. */
export interface CatalogSite {
  about: Translated;
  highlights: Translated[];
  /** Priced lines that are shown but not booked: a cafe's menu. */
  showcase: { title: Translated; items: CatalogService[] }[];
}

export interface Catalog {
  /** The tenant the booking API is told about. */
  slug: string;
  salon: Salon;
  groups: CatalogGroup[];
  services: CatalogService[];
  masters: Master[];
  theme: ThemeDef;
  /** "Мастер", "Бокс", "Столик": what step two picks. */
  staffLabel: Translated;
  site: CatalogSite | null;
  /** The built-in module keeps its online-payment step and /bookings list. */
  legacy: boolean;
}

const CHINOR_GROUPS = ["hair", "beard", "color", "nails", "brows"] as const;

export const CHINOR_CATALOG: Catalog = {
  slug: chinorSalon.id,
  salon: chinorSalon,
  groups: CHINOR_GROUPS.map((id) => ({
    id,
    title: { ru: dictionaries.ru[`group.${id}`], uz: dictionaries.uz[`group.${id}`] },
  })),
  services: chinorServices,
  masters: chinorMasters,
  theme: THEMES.turquoise,
  staffLabel: STAFF_LABEL.salon,
  site: null,
  legacy: true,
};

/** Tolerates a spec that is mid-edit in the builder (empty numbers, no staff). */
export function catalogFromSpec(spec: SiteSpec): Catalog {
  const number = (value: unknown) => (Number.isFinite(Number(value)) ? Number(value) : 0);

  const toService = (item: SiteSpec["items"][number]): CatalogService => ({
    id: item.id,
    group: item.categoryId,
    title: item.title,
    description: item.description,
    durationMin: number(item.durationMin),
    priceSum: number(item.priceSum),
    popular: item.popular,
  });

  const bookable = spec.items.filter((item) => item.bookable);
  const shown = spec.items.filter((item) => !item.bookable);

  return {
    slug: spec.slug,
    salon: {
      id: spec.slug,
      name: spec.name,
      tagline: spec.tagline,
      address: spec.address,
      phone: spec.phone ? `998${spec.phone}` : "",
      // Generated sites carry no ratings: there are no reviews to count yet.
      rating: 0,
      reviewCount: 0,
      openFrom: spec.hours.from,
      openTo: spec.hours.to,
    },
    groups: spec.categories.filter((category) =>
      bookable.some((item) => item.categoryId === category.id),
    ),
    services: bookable.map(toService),
    masters: spec.staff.map((member) => ({
      id: member.id,
      name: member.name,
      craft: member.role,
      rating: 0,
      reviewCount: 0,
      serviceIds: member.itemIds,
      workdays: member.workdays,
      shiftStart: member.shiftStart,
      shiftEnd: member.shiftEnd,
      busy: {},
      tint: member.tint,
    })),
    theme: THEMES[spec.theme] ?? THEMES.turquoise,
    staffLabel: STAFF_LABEL[spec.kind] ?? STAFF_LABEL.custom,
    site: {
      about: spec.about,
      highlights: spec.highlights,
      showcase: spec.categories
        .map((category) => ({
          title: category.title,
          items: shown.filter((item) => item.categoryId === category.id).map(toService),
        }))
        .filter((section) => section.items.length > 0),
    },
    legacy: false,
  };
}

const CatalogContext = createContext<Catalog>(CHINOR_CATALOG);

export function CatalogProvider({ value, children }: { value: Catalog; children: ReactNode }) {
  return <CatalogContext.Provider value={value}>{children}</CatalogContext.Provider>;
}

export function useCatalog(): Catalog {
  return useContext(CatalogContext);
}

export function totalFor(
  services: CatalogService[],
  serviceIds: string[],
): { sum: number; minutes: number } {
  return serviceIds.reduce(
    (total, id) => {
      const service = services.find((entry) => entry.id === id);
      if (!service) return total;
      return { sum: total.sum + service.priceSum, minutes: total.minutes + service.durationMin };
    },
    { sum: 0, minutes: 0 },
  );
}

/** Price and length of the draft, from the catalogue actually on screen. */
export function useDraftTotal(): { sum: number; minutes: number } {
  const { draft } = useBooking();
  const { services } = useCatalog();
  return useMemo(() => totalFor(services, draft.serviceIds), [services, draft.serviceIds]);
}

/**
 * Re-points the brand tokens for one tenant. The Tailwind utilities read
 * `var(--color-brand)` and friends, so setting them on a wrapper restyles
 * everything inside without a second set of classes.
 */
export function themeStyle(theme: ThemeDef): CSSProperties {
  return {
    "--color-brand": theme.brand,
    "--color-brand-ink": "#ffffff",
    "--color-accent": theme.accent,
  } as CSSProperties;
}
