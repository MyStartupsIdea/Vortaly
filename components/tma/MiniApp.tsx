/* ----------------------------------------------------------------- phone --- */

/** Keep only the nine national digits: +998 is fixed in the field itself. */
function normalisePhone(raw: string): string {
  let digits = raw.replace(/\D/g, "");
  if (digits.startsWith("998")) digits = digits.slice(3);
  return digits.slice(0, 9);
}

/** 901234567 -> "90 123 45 67" */
function groupPhone(digits: string): string {
  return [digits.slice(0, 2), digits.slice(2, 5), digits.slice(5, 7), digits.slice(7, 9)]
    .filter(Boolean)
    .join(" ");
}

/* --------------------------------------------------------------- section --- */

interface SectionProps {
  index: number;
  title: string;
  /** Shown in the collapsed header once the step has an answer. */
  answer: ReactNode;
  open: boolean;
  done: boolean;
  enabled: boolean;
  onToggle: () => void;
  children: ReactNode;
}

function Section({
  index,
  title,
  answer,
  open,
  done,
  enabled,
  onToggle,
  children,
}: SectionProps) {
  return (
    <section
      className={cx(
        "glaze mx-4 mt-3 rounded-card transition-shadow duration-150",
        open && "shadow-[inset_0_0_0_2px_var(--color-brand)]",
        !enabled && "opacity-50",
      )}
    >
      <h2>
        <button
          type="button"
          disabled={!enabled}
          aria-expanded={open}
          onClick={onToggle}
          className="flex w-full items-center gap-3 px-4 py-4 text-left"
        >
          {/* Numbered because booking really is a sequence, not decoration. */}
          <span
            aria-hidden
            className={cx(
              "grid size-7 flex-none place-items-center rounded-full font-display text-[13px] font-semibold tabular-nums",
              done || open
                ? "glaze-brand text-brand-ink"
                : "bg-surface-sunken text-ink-muted",
            )}
          >
            {done ? (
              <svg viewBox="0 0 14 14" className="size-3.5 stroke-current" fill="none">
                <path
                  d="M2.5 7.5 5.5 10.5 11.5 3.5"
                  strokeWidth="2.4"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                />
              </svg>
            ) : (
              index
            )}
          </span>

          <span className="min-w-0 flex-1">
            <span className="block font-display text-[15px] font-semibold tracking-[-0.01em]">
              {title}
            </span>
            {!open && (
              <span className="mt-0.5 block truncate text-[13px] text-ink-muted">{answer}</span>
            )}
          </span>

          <svg
            aria-hidden
            viewBox="0 0 16 16"
            fill="none"
            className={cx(
              "size-4 flex-none stroke-ink-muted transition-transform duration-200",
              open && "rotate-90",
            )}
          >
            <path d="M6 3l5 5-5 5" strokeWidth="1.8" strokeLinecap="round" />
          </svg>
        </button>
      </h2>

      {open && <div className="pb-4">{children}</div>}
    </section>
  );
}

/* ------------------------------------------------------------------ page --- */

const PAY_OPTIONS: { value: PayMethod; labelKey: "pay.cash" | "pay.click" | "pay.payme" }[] = [
  { value: "cash", labelKey: "pay.cash" },
  { value: "click", labelKey: "pay.click" },
  { value: "payme", labelKey: "pay.payme" },
];

type StepIndex = 1 | 2 | 3 | 4;

/**
 * The booking flow for one tenant. The tenant is whatever catalogue is in
 * context: the built-in Chinor module by default, or a site generated by the
 * builder (see components/tma/TenantSite.tsx).
 *
 * `preview` is the builder's live preview: everything is interactive except
 * the final submit, which must not create bookings for an unpublished draft.
 */
/** Nothing is taken in a preview or before a day is chosen; one stable empty list. */
const NO_TAKEN: BusySpan[] = [];

export function MiniApp({ preview = false }: { preview?: boolean } = {}) {
  const router = useRouter();
  const { draft, setField, setTime, resetDraft, hydrated } = useBooking();
  const catalog = useCatalog();
  const total = useDraftTotal();
  const { locale } = useLocale();
  const { t, tr } = useI18n();
  const { user, webApp, haptic } = useTelegram();

  const [open, setOpen] = useState(1);
  /** Other customers' appointments on the chosen day, from the server. */
  const [takenFetched, setTaken] = useState<BusySpan[]>([]);
  /** A generated tenant confirms in place; it has no /bookings list of its own. */
  const [confirmed, setConfirmed] = useState<{
    date: string;
    time: string;
    stored: boolean;
  } | null>(null);

  /* The draft is kept in one localStorage slot for every tenant. A draft made
     at another business names services that do not exist here, so it is
     dropped rather than shown as a selection nobody can see. */
  useEffect(() => {
    if (!hydrated) return;
    const strangers =
      draft.serviceIds.some((id) => !catalog.services.some((s) => s.id === id)) ||
      (draft.masterId !== null &&
        draft.masterId !== "any" &&
        !catalog.masters.some((m) => m.id === draft.masterId));
    if (strangers) resetDraft();
  }, [hydrated, draft.serviceIds, draft.masterId, catalog.services, catalog.masters, resetDraft]);

  /* Slots other people already took. Failing to learn them is not fatal: the
     server still refuses a double booking, the grid is just less informed. */
  useEffect(() => {
    if (preview || !draft.date) return;
    let cancelled = false;
    fetch(`/api/bookings/busy?date=${draft.date}`, {
      headers: { "X-Vortaly-Tenant": catalog.slug },
      cache: "no-store",
    })
      .then((response) => (response.ok ? response.json() : { busy: [] }))
      .then((body: { busy?: BusySpan[] }) => {
        if (!cancelled) setTaken(Array.isArray(body.busy) ? body.busy : []);
      })
      .catch(() => {
        if (!cancelled) setTaken([]);
      });
    return () => {
      cancelled = true;
    };
  }, [preview, draft.date, catalog.slug]);
  const taken = preview || !draft.date ? NO_TAKEN : takenFetched;
  const [sending, setSending] = useState(false);
  /* A refused attempt explains itself in two short lines. The server's own
     text is never quoted: it is machinery, and the customer needs to know
     what happened to their answers, not what the API said. */
  const [failure, setFailure] = useState<{ message: string; hint: string } | null>(null);
  const [activeCount, setActiveCount] = useState(0);

  // Read after mount only: the booking store answers with a seed during SSR,
  // and putting that count in the static HTML would mismatch on hydration.
  useEffect(() => {
    if (!hydrated) return;
    setActiveCount(getBookings().filter((b) => b.status !== "cancelled").length);
  }, [hydrated]);

  // Telegram already knows who this is; asking again would be busywork.
  useEffect(() => {
    if (user?.first_name && !draft.name) setField("name", user.first_name);
  }, [user, draft.name, setField]);

  const phoneDigits = normalisePhone(draft.phone);
  const phoneValid = /^\d{9}$/.test(phoneDigits);
  const nameValid = draft.name.trim().length > 1;

  const done = useMemo<Record<StepIndex, boolean>>(
    () => ({
      1: draft.serviceIds.length > 0,
      2: draft.masterId !== null,
      3: Boolean(draft.date && draft.time),
      4: nameValid && phoneValid,
    }),
    [draft.serviceIds.length, draft.masterId, draft.date, draft.time, nameValid, phoneValid],
  );

  const ready = done[1] && done[2] && done[3] && done[4];
  const firstIncomplete: StepIndex = ([1, 2, 3, 4] as StepIndex[]).find((n) => !done[n]) ?? 4;

  /** A step opens only once every step before it has an answer. */
  const enabled = (index: number) =>
    ([1, 2, 3, 4] as StepIndex[]).filter((n) => n < index).every((n) => done[n]);

  const toggle = (index: number) => () => setOpen((current) => (current === index ? 0 : index));

  /**
   * What a status means for the person filling the form. None of these answers
   * discards the draft by itself — that is decided by the caller, so a refusal
   * never costs someone the name and phone they just typed.
   */
  function problemFor(status: number) {
    if (status === 409) {
      return { message: t("error.slotTaken"), hint: t("error.slotTakenHint") };
    }
    if (status === 400 || status === 422) {
      return { message: t("error.rejected"), hint: t("error.rejectedHint") };
    }
    if (status === 401 || status === 403) {
      return { message: t("error.identity"), hint: t("error.identityHint") };
    }
    if (status === 502 || status === 503 || status === 504) {
      return { message: t("error.unavailable"), hint: t("error.unavailableHint") };
    }
    return { message: t("error.generic"), hint: t("error.genericHint") };
  }

  async function submit() {
    setFailure(null);
    if (preview) {
      setFailure({ message: t("site.previewOnly"), hint: t("site.previewOnlyHint") });
      return;
    }
    setSending(true);
    haptic("press");

    try {
      /* Who is booking is proved by the signed initData Telegram handed the
         Mini App, not claimed in the payload: the server verifies the
         signature with the bot token and takes the Telegram id from there.
         Sending `user.id` would be sending an unsigned number the server is
         right to ignore. Outside Telegram there is no initData to send, and
         the server decides what an unverified caller may do. */
      const initData = webApp?.initData;

      const response = await fetch("/api/bookings", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          /* Names the tenant when the page is served from the platform host
             (/<slug>) rather than the tenant's own subdomain. The proxy checks
             it against the database; on a subdomain the host wins. */
          "X-Vortaly-Tenant": catalog.slug,
          ...(initData ? { "X-Telegram-Init-Data": initData } : {}),
        },
        body: JSON.stringify({
          masterId: draft.masterId === "any" ? firstFreeMaster() : draft.masterId,
          serviceIds: draft.serviceIds,
          date: draft.date,
          time: draft.time,
          customerName: draft.name.trim(),
          customerPhone: "+998" + phoneDigits,
        }),
      });

      /* A refused slot is not a failed booking: the data is fine and only the
         minute was taken, so only the minute is cleared and the time step is
         reopened. Validation and outage answers keep the whole draft, because
         it is the thing that would be expensive to retype. */
      if (!response.ok) {
        haptic("error");
        setFailure(problemFor(response.status));
        if (response.status === 409) {
          setTime(null);
          setOpen(3);
        }
        setSending(false);
        return;
      }

      /* The endpoint answers with the save outcome alongside the booking. A
         201 only means it replied — it does not mean a row exists, so the
         outcome is read rather than assumed. */
      const result = (await response.json()) as {
        booking: Booking;
        persisted?: boolean;
        warning?: string;
      };
      const booking = result.booking;
      const state = classifySave(result);
      const stored = isSaved(state);

      // Into the shared store, so the slot just taken is blocked for everyone
      // and the booking appears under "my bookings" — tagged with whether the
      // server actually kept it.
      createBooking(booking, stored ? "server" : "local");

      haptic(stored ? "success" : "error");
      resetDraft();

      if (!catalog.legacy) {
        setConfirmed({ date: booking.date, time: booking.time, stored });
        setSending(false);
        setOpen(1);
        return;
      }

      /* An unsaved booking goes to the list, never to checkout: asking someone
         to pay for a record the salon never received would be the worst
         possible place to hide this state. The list states it outright. */
      router.push(
        !stored
          ? "/bookings?created=" + booking.id + "&save=" + state
          : draft.payMethod === "cash"
            ? "/bookings?created=" + booking.id + "&save=" + state
            : "/checkout/" + booking.id + "?provider=" + draft.payMethod,
      );
    } catch {
      // Offline, aborted, or not JSON: same reassurance, draft untouched.
      haptic("error");
      setFailure({ message: t("error.generic"), hint: t("error.genericHint") });
      setSending(false);
    }
  }

  const serviceAnswer =
    draft.serviceIds.length === 0
      ? t("tma.notChosen")
      : draft.serviceIds
          .map((id) => {
            const service = catalog.services.find((entry) => entry.id === id);
            return service ? tr(service.title) : null;
          })
          .filter(Boolean)
          .join(", ");

  const masterAnswer =
    draft.masterId === null
      ? t("tma.notChosen")
      : draft.masterId === "any"
        ? t("master.anyTitle")
        : (catalog.masters.find((m) => m.id === draft.masterId)?.name ?? t("tma.notChosen"));

  /**
   * "First available" is a choice for the customer, not for the API: a booking
   * row needs a real master. This picks the first one who performs every chosen
   * service, works that day, and is not already busy at the chosen minute.
   */
  function firstFreeMaster(): string | null {
    if (!draft.date || !draft.time) return null;
    const able = catalog.masters.filter((m) =>
      draft.serviceIds.every((id) => m.serviceIds.includes(id)),
    );
    const slot = buildSlots({
      masterId: "any",
      isoDate: draft.date,
      durationMin: total.minutes,
      masters: catalog.masters,
      candidates: able,
      taken,
    }).find((entry) => entry.time === draft.time);
    return slot?.freeMasterIds[0] ?? able[0]?.id ?? null;
  }

  const timeAnswer =
    draft.date && draft.time
      ? formatDayMonth(fromIsoDate(draft.date), locale) + ", " + draft.time
      : t("tma.notChosen");

  const contactAnswer = done[4]
    ? draft.name.trim() + ", +998 " + groupPhone(phoneDigits)
    : t("tma.notChosen");

  const payAnswer = t(PAY_OPTIONS.find((o) => o.value === draft.payMethod)!.labelKey);

  const actionLabel = ready
    ? sending
      ? t("confirm.sending")
      : t("confirm.submit")
    : firstIncomplete === 1
      ? t("error.pickService")
      : firstIncomplete === 2
        ? catalog.legacy
          ? t("error.pickMaster")
          : `${t("site.choose")}: ${tr(catalog.staffLabel).toLowerCase()}`
        : firstIncomplete === 3
          ? t("error.pickTime")
          : t("tma.contacts");

  return (
    <main
      className={cx("flex flex-col bg-surface", preview ? "min-h-full" : "min-h-screen")}
      style={themeStyle(catalog.theme)}
    >
      <SalonHeader />

      <SiteIntro />

      {confirmed && (
        <div
          role="status"
          className={cx(
            "mx-5 mt-5 rounded-card border p-4",
            confirmed.stored ? "border-brand/45 bg-brand/8" : "border-saffron/50 bg-saffron/10",
          )}
        >
          <p className="font-display text-[16px] font-bold">
            {confirmed.stored ? t("site.booked") : t("site.bookedLocal")}
          </p>
          <p className="mt-1 text-[14px] tabular-nums">
            {formatDayMonth(fromIsoDate(confirmed.date), locale)}, {confirmed.time}
          </p>
          <p className="mt-2 text-[13px] leading-snug text-ink-muted">
            {confirmed.stored ? t("site.bookedHint") : t("site.bookedLocalHint")}
          </p>
          <button
            type="button"
            onClick={() => setConfirmed(null)}
            className="mt-3 text-[13px] font-semibold text-brand"
          >
            {t("site.bookAgain")}
          </button>
        </div>
      )}

      {catalog.legacy && activeCount > 0 && (
        <Link
          href="/bookings"
          className="glaze mx-4 mt-3 flex items-center justify-between gap-3 rounded-card px-4 py-3 text-[14px]"
        >
          <span className="font-semibold">{t("nav.bookings")}</span>
          <span className="flex items-center gap-2 text-ink-muted">
            <span className="grid size-5 place-items-center rounded-full bg-brand text-[11px] font-bold text-brand-ink tabular-nums">
              {activeCount}
            </span>
            <svg viewBox="0 0 16 16" fill="none" className="size-4 stroke-current">
              <path d="M6 3l5 5-5 5" strokeWidth="1.8" strokeLinecap="round" />
            </svg>
          </span>
        </Link>
      )}

      <div className="flex-1">
        {catalog.site && (
          <h2 className="px-5 pt-6 pb-1 font-display text-[19px] font-semibold tracking-[-0.02em]">
            {t("site.bookOnline")}
          </h2>
        )}
        {catalog.services.length === 0 && (
          <p className="px-5 py-6 text-[14px] text-ink-muted">{t("site.nothingBookable")}</p>
        )}
        <Section
          index={1}
          title={t("step.services")}
          answer={serviceAnswer}
          open={open === 1}
          done={done[1]}
          enabled
          onToggle={toggle(1)}
        >
          <ServiceList />
        </Section>

        <Section
          index={2}
          title={catalog.legacy ? t("step.master") : tr(catalog.staffLabel)}
          answer={masterAnswer}
          open={open === 2}
          done={done[2]}
          enabled={enabled(2)}
          onToggle={toggle(2)}
        >
          <MasterList onPicked={() => setOpen(3)} />
        </Section>

        <Section
          index={3}
          title={t("step.time")}
          answer={timeAnswer}
          open={open === 3}
          done={done[3]}
          enabled={enabled(3)}
          onToggle={toggle(3)}
        >
          <Calendar />
          <SlotGrid
            taken={taken}
            onPicked={() => {
              setOpen(4);
              // "Choose another time" is answered as soon as a slot is picked.
              setFailure(null);
            }}
          />
        </Section>

        <Section
          index={4}
          title={t("tma.contacts")}
          answer={contactAnswer}
          open={open === 4}
          done={done[4]}
          enabled={enabled(4)}
          onToggle={toggle(4)}
        >
          <div className="space-y-4 px-4">
            <label className="block">
              <span className="block text-[13px] text-ink-muted">{t("confirm.name")}</span>
              <input
                value={draft.name}
                onChange={(e) => setField("name", e.target.value)}
                placeholder={t("confirm.namePlaceholder")}
                autoComplete="name"
                className="mt-1.5 w-full rounded-tile border border-hairline bg-surface-raised px-3.5 py-3 text-[16px] outline-none placeholder:text-ink-muted/70 focus:border-brand focus:shadow-[0_0_0_3px_color-mix(in_srgb,var(--color-brand)_12%,transparent)]"
              />
            </label>

            <label className="block">
              <span className="block text-[13px] text-ink-muted">{t("confirm.phone")}</span>
              {/* The country code is fixed rather than typed: every customer
                  here is on +998, and a prefix cannot be fat-fingered. */}
              <span className="mt-1.5 flex items-center rounded-tile border border-hairline bg-surface-raised focus-within:border-brand focus-within:shadow-[0_0_0_3px_color-mix(in_srgb,var(--color-brand)_12%,transparent)]">
                <span className="pl-4 text-[16px] font-semibold text-ink-muted tabular-nums">
                  +998
                </span>
                <input
                  value={groupPhone(phoneDigits)}
                  onChange={(e) => setField("phone", normalisePhone(e.target.value))}
                  placeholder="90 123 45 67"
                  inputMode="numeric"
                  autoComplete="tel-national"
                  className="w-full bg-transparent px-3 py-3 text-[16px] tabular-nums outline-none placeholder:text-ink-muted/60"
                />
              </span>
              {phoneDigits.length > 0 && !phoneValid && (
                <span className="mt-1.5 block text-[12px] text-accent">{t("error.phone")}</span>
              )}
            </label>
          </div>
        </Section>

        {/* Online payment exists only in the built-in module, and only as a
            stub. A generated tenant takes payment at the venue until the
            Click/Payme callbacks are real. */}
        {catalog.legacy && <Section
          index={5}
          title={t("pay.method")}
          answer={payAnswer}
          done={ready}
          open={open === 5}
          enabled={enabled(5)}
          onToggle={toggle(5)}
        >
          <div className="grid grid-cols-3 gap-1.5 px-5">
            {PAY_OPTIONS.map((option) => {
              const active = draft.payMethod === option.value;
              return (
                <button
                  key={option.value}
                  type="button"
                  aria-pressed={active}
                  onClick={() => {
                    setField("payMethod", option.value);
                    haptic("select");
                  }}
                  className={cx(
                    "rounded-tile px-2 py-3 text-[13px] font-semibold transition-colors duration-150",
                    active ? "glaze-brand text-brand-ink" : "glaze border border-hairline",
                  )}
                >
                  {t(option.labelKey)}
                </button>
              );
            })}
          </div>
          <p className="mt-3 px-5 text-[12px] text-ink-muted">{t("pay.hint")}</p>
        </Section>}
        {!catalog.legacy && (
          <p className="px-5 pt-4 text-[12px] leading-snug text-ink-muted">{t("site.payAtVenue")}</p>
        )}

        {failure && (
          <div role="alert" className="px-5 pt-4">
            <p className="text-[13px] font-semibold text-accent">{failure.message}</p>
            <p className="mt-1 text-[12px] leading-snug text-ink-muted">{failure.hint}</p>
          </div>
        )}
      </div>

      <ActionBar>
        <div className="flex items-center gap-3">
        {done[1] && (
          <div className="min-w-0 flex-1">
            <p className="font-display text-[18px] leading-tight font-semibold tabular-nums">
              {total.sum > 0 ? formatSum(total.sum, locale) : t("site.free")}
            </p>
            <p className="truncate text-[12px] text-ink-muted">
              {t("action.selected", { count: draft.serviceIds.length })} · {formatDuration(total.minutes, locale)}
            </p>
          </div>
        )}

        <Button
          block={!done[1]}
          className={done[1] ? "max-w-[60%] flex-none" : undefined}
          disabled={sending}
          onClick={() => {
            if (ready) {
              submit();
              return;
            }
            // Jump to whatever is still missing instead of refusing silently.
            setOpen(firstIncomplete);
            haptic("press");
          }}
        >
          <span className="truncate">{actionLabel}</span>
        </Button>
        </div>
      </ActionBar>
    </main>
  );
}
